-- Luxcord database upgrade
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (length(username) between 3 and 32),
  display_name text not null,
  bio text not null default '',
  status text not null default 'Online',
  settings jsonb not null default '{"sound":true,"notifications":true,"enter_send":true,"theme":"dark"}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester uuid not null references public.profiles(id) on delete cascade,
  addressee uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check(status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  unique(requester,addressee),
  check(requester <> addressee)
);

alter table public.chat_messages add column if not exists user_id uuid references public.profiles(id) on delete set null;
alter table public.chat_messages add column if not exists reply_to bigint references public.chat_messages(id) on delete set null;

create table if not exists public.message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.chat_messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null,
  unique(message_id,user_id,emoji)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,
  title text not null,
  body text not null,
  data jsonb not null default '{}'::jsonb,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.dm_conversations (
  id bigint generated by default as identity primary key,
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(user_a,user_b),
  check(user_a < user_b)
);

create table if not exists public.dm_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.dm_conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  message text not null check(length(message) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.dm_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.dm_messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null,
  unique(message_id,user_id,emoji)
);

create or replace function public.create_notification(target_user uuid, notification_type text, notification_title text, notification_body text, notification_data jsonb default '{}'::jsonb)
returns void language sql security definer set search_path=public as $$
  insert into public.notifications(user_id,type,title,body,data) values(target_user,notification_type,notification_title,notification_body,notification_data);
$$;

