create policy "profiles readable" on public.profiles for select to authenticated using (true);
create policy "own profile update" on public.profiles for update to authenticated using (auth.uid()=id) with check(auth.uid()=id);
create policy "own profile insert" on public.profiles for insert to authenticated with check(auth.uid()=id);

create policy "friendships visible to participants" on public.friendships for select to authenticated using (auth.uid()=requester or auth.uid()=addressee);
create policy "send friend requests" on public.friendships for insert to authenticated with check(auth.uid()=requester);
create policy "update received requests" on public.friendships for update to authenticated using (auth.uid()=addressee) with check (auth.uid()=addressee);

create policy "reactions readable" on public.message_reactions for select to authenticated using (true);
create policy "own reactions insert" on public.message_reactions for insert to authenticated with check(auth.uid()=user_id);
create policy "own reactions delete" on public.message_reactions for delete to authenticated using(auth.uid()=user_id);

create policy "own notifications" on public.notifications for select to authenticated using(auth.uid()=user_id);
create policy "own notifications update" on public.notifications for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);

create policy "conversation participants read" on public.dm_conversations for select to authenticated using(auth.uid()=user_a or auth.uid()=user_b);
create policy "conversation participants create" on public.dm_conversations for insert to authenticated with check(auth.uid()=user_a or auth.uid()=user_b);

create policy "dm messages participants read" on public.dm_messages for select to authenticated using(exists(select 1 from public.dm_conversations c where c.id=conversation_id and (c.user_a=auth.uid() or c.user_b=auth.uid())));
create policy "dm messages own insert" on public.dm_messages for insert to authenticated with check(auth.uid()=sender_id and exists(select 1 from public.dm_conversations c where c.id=conversation_id and (c.user_a=auth.uid() or c.user_b=auth.uid())));

create policy "dm reactions participants read" on public.dm_reactions for select to authenticated using(exists(select 1 from public.dm_messages m join public.dm_conversations c on c.id=m.conversation_id where m.id=message_id and (c.user_a=auth.uid() or c.user_b=auth.uid())));
create policy "own dm reactions insert" on public.dm_reactions for insert to authenticated with check(auth.uid()=user_id);
create policy "own dm reactions delete" on public.dm_reactions for delete to authenticated using(auth.uid()=user_id);

